/// New device: generate an ephemeral X25519 keypair for provisioning.
/// The secret is stored in CryptoState. Only the pubkey is returned.
#[tauri::command]
pub fn provision_create_session(state: tauri::State<'_, CryptoState>) -> Result<String, String> {
    let mut ephemeral_secret = [0u8; 32];
    rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut ephemeral_secret);

    let ephemeral_public =
        x25519_dalek::PublicKey::from(&x25519_dalek::StaticSecret::from(ephemeral_secret));
    let pubkey_hex = hex::encode(ephemeral_public.as_bytes());

    *lock_mutex(&state.provisioning_ephemeral)? = Some(ephemeral_secret);

    Ok(pubkey_hex)
}

/// New device: compute the provisioning SAS code from the stored ephemeral secret
/// and the primary device's encryption pubkey. The SAS is displayed for verification.
#[tauri::command]
pub fn provision_compute_sas(
    state: tauri::State<'_, CryptoState>,
    primary_enc_pubkey_hex: String,
) -> Result<String, String> {
    let guard = lock_mutex(&state.provisioning_ephemeral)?;
    let ephemeral_secret = guard.as_ref().ok_or_else(|| {
        "No provisioning session. Call provision_create_session first.".to_string()
    })?;

    // Compute shared secret and derive SAS (same as Rust provisioning module).
    // parse_x25519_pubkey validates: 32-byte x-only format, rejects all-zeros identity point.
    let eph_sk = x25519_dalek::StaticSecret::from(*ephemeral_secret);
    let primary_pk = llamenos_core::provisioning::parse_x25519_pubkey(&primary_enc_pubkey_hex)
        .map_err(err_str)?;

    let shared = eph_sk.diffie_hellman(&primary_pk);
    let shared_bytes = shared.as_bytes();
    if *shared_bytes == [0u8; 32] {
        return Err("ECDH shared secret is all-zeros (low-order point)".into());
    }

    // SAS derivation: HKDF(ikm=shared, salt=SAS_SALT, info=SAS_INFO, len=4)
    let hk = hkdf::Hkdf::<sha2::Sha256>::new(
        Some(llamenos_core::labels::SAS_SALT.as_bytes()),
        shared_bytes,
    );
    let mut sas_bytes = [0u8; 4];
    hk.expand(llamenos_core::labels::SAS_INFO.as_bytes(), &mut sas_bytes)
        .map_err(|e| format!("HKDF expand failed: {e}"))?;

    let num = (sas_bytes[0] as u32) << 24
        | (sas_bytes[1] as u32) << 16
        | (sas_bytes[2] as u32) << 8
        | sas_bytes[3] as u32;
    let code = format!("{:06}", num % 1_000_000);
    Ok(format!("{} {}", &code[..3], &code[3..]))
}

/// New device: decrypt the provisioned key bundle and import it as device keys.
/// The decrypted seeds NEVER enter JavaScript — they go directly from decryption
/// into CryptoState, encrypted with the user's PIN.
/// Returns the PIN-encrypted device key blob for persistent storage.
#[tauri::command]
pub fn provision_decrypt_and_import(
    state: tauri::State<'_, CryptoState>,
    encrypted_hex: String,
    primary_enc_pubkey_hex: String,
    pin: String,
    device_id: String,
) -> Result<serde_json::Value, String> {
    // Take the ephemeral secret out (consumed — one-shot)
    let ephemeral_secret = lock_mutex(&state.provisioning_ephemeral)?
        .take()
        .ok_or_else(|| {
            "No provisioning session. Call provision_create_session first.".to_string()
        })?;

    // Decrypt the provisioned payload — returns BOTH device seeds.
    //
    // Both seeds are used exactly as transported. Re-deriving the encryption
    // seed from the signing seed here (as this command used to do) gives the
    // linked device a different X25519 key than the one existing ciphertext was
    // wrapped to: it authenticates fine and decrypts nothing, with no error on
    // either side. See packages/crypto/src/provisioning.rs and its
    // `linked_device_decrypts_ciphertext_wrapped_to_primary` regression test.
    let decrypted = llamenos_core::provisioning::decrypt_provisioned_bundle(
        &encrypted_hex,
        &primary_enc_pubkey_hex,
        &ephemeral_secret,
    )
    .map_err(err_str)?;

    let secrets = decrypted.secrets;

    let device_state = device_keys::DeviceKeyState {
        device_id: device_id.clone(),
        signing_pubkey_hex: hex::encode(secrets.signing_pubkey().to_bytes()),
        encryption_pubkey_hex: hex::encode(secrets.encryption_pubkey().to_bytes()),
    };

    // Encrypt with PIN for persistent storage
    let encrypted_keys = encrypt_secrets_with_pin(&secrets, &pin, &device_state)?;

    // Load into CryptoState
    *lock_mutex(&state.secrets)? = Some(secrets);
    *lock_mutex(&state.device_state)? = Some(device_state);

    serde_json::to_value(&encrypted_keys).map_err(err_str)
}

// ── Internal helpers ────────────────────────────────────────────────

/// Derive X25519 encryption seed from Ed25519 signing seed via HKDF.
///
/// ONLY for importing a single-seed identity that has no separate encryption
/// seed to import — i.e. `device_import_and_load`, whose seeds come from
/// `scripts/bootstrap-admin.ts` / `apps/worker/lib/demo-crypto.ts`, which
/// publish an X25519 pubkey derived this same way.
///
/// MUST NOT be used for device linking or anywhere a real encryption seed
/// exists: a device that re-derives its encryption key instead of receiving it
/// holds the wrong X25519 key and silently decrypts nothing, and the derivation
/// collapses PROTOCOL.md §2.11's independence guarantee (holding the signing
/// seed would mean holding the decryption key).
fn derive_encryption_seed_from_signing(signing_seed: &[u8; 32]) -> [u8; 32] {
    let hk = hkdf::Hkdf::<sha2::Sha256>::new(None, signing_seed);
    let mut encryption_seed = [0u8; 32];
    hk.expand(
        LABEL_DEVICE_ENCRYPTION_SEED.as_bytes(),
        &mut encryption_seed,
    )
    .expect("HKDF expand for encryption seed failed");
    encryption_seed
}

/// Encrypt device secrets with a PIN, producing an EncryptedDeviceKeys blob.
/// This mirrors the logic in device_keys::generate_device_keys but for imported seeds.
fn encrypt_secrets_with_pin(
    secrets: &device_keys::DeviceSecrets,
    credential: &str,
    device_state: &device_keys::DeviceKeyState,
) -> Result<device_keys::EncryptedDeviceKeys, String> {
    // Generate salt and nonce
    let mut salt = [0u8; 32];
    let mut nonce_bytes = [0u8; 12];
    rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut salt);
    rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut nonce_bytes);

    // Derive KEK with Argon2id (using llamenos_core's parameters)
    use argon2::Argon2;
    let argon2 = Argon2::new(
        argon2::Algorithm::Argon2id,
        argon2::Version::V0x13,
        argon2::Params::new(65_536, 3, 4, Some(32)).map_err(|e| format!("Argon2 params: {e}"))?,
    );
    let mut kek = [0u8; 32];
    argon2
        .hash_password_into(credential.as_bytes(), &salt, &mut kek)
        .map_err(|e| format!("Argon2id derivation failed: {e}"))?;

    let nonce = Nonce::from_slice(&nonce_bytes);
    let cipher = Aes256Gcm::new_from_slice(&kek).map_err(|e| format!("Invalid KEK: {e}"))?;

    // Concatenate signing_seed || encryption_seed
    let mut plaintext = Vec::with_capacity(64);
    plaintext.extend_from_slice(&secrets.signing_seed);
    plaintext.extend_from_slice(&secrets.encryption_seed);

    let ciphertext = cipher
        .encrypt(nonce, plaintext.as_ref())
        .map_err(|e| format!("Encryption failed: {e}"))?;

    Ok(device_keys::EncryptedDeviceKeys {
        kdf_version: 2,
        salt: hex::encode(salt),
        argon2_m_cost: 65_536,
        argon2_t_cost: 3,
        argon2_p_cost: 4,
        nonce: hex::encode(nonce_bytes),
        ciphertext: hex::encode(ciphertext),
        state: device_state.clone(),
    })
}

/// Decrypt a server-published relay event using the epoch-keyed server event key.
/// Input: hex-encoded nonce(12) + ciphertext + epoch number.
/// AAD: `"{LABEL_HUB_EVENT_EPOCH}:{epoch}"` for domain separation (epoch-keyed events
/// use LABEL_HUB_EVENT_EPOCH, not LABEL_HUB_EVENT which is for hub-key-encrypted events).
/// Returns the event's JSON, with the server's bucket padding stripped.
#[tauri::command]
pub fn decrypt_server_event(
    state: tauri::State<'_, CryptoState>,
    ciphertext_hex: String,
    epoch: u64,
) -> Result<String, String> {
    let keys = lock_mutex(&state.server_event_keys)?;
    open_server_event(&keys, &ciphertext_hex, epoch)
}

/// The body of [`decrypt_server_event`], free of Tauri state so it can be tested.
///
/// The server pads every event to a power-of-2 bucket before sealing it
/// (`apps/worker/lib/hub-event-crypto.ts` `padToBucket`, the same format as
/// [`llamenos_core::padding::pad_to_bucket`]):
/// `[4-byte LE length][JSON][random padding]`. The plaintext must be unpadded
/// before it is UTF-8 decoded. Returning the padded buffer instead failed every
/// event — the random tail is not UTF-8, and when it happened to be, the length
/// prefix still made the JSON unparseable — and the relay client drops an
/// undecodable event without a trace, so no desktop handler ever ran (#2046).
/// Mobile's `mobile_decrypt_server_event_with_epoch` already unpads.
fn open_server_event(
    keys: &[(u64, Vec<u8>)],
    ciphertext_hex: &str,
    epoch: u64,
) -> Result<String, String> {
    let key = keys
        .iter()
        .find(|(e, _)| *e == epoch)
        .map(|(_, k)| k)
        .ok_or_else(|| format!("No server event key for epoch {epoch}"))?;

    let data = hex::decode(ciphertext_hex).map_err(err_str)?;
    if data.len() < 28 {
        return Err("Ciphertext too short (need at least 12-byte nonce + 16-byte tag)".into());
    }

    let aad = format!("{LABEL_HUB_EVENT_EPOCH}:{epoch}");
    let nonce = Nonce::from_slice(&data[..12]);
    let cipher =
        Aes256Gcm::new_from_slice(key).map_err(|e| format!("Invalid server event key: {e}"))?;
    let padded = cipher
        .decrypt(
            nonce,
            Payload {
                msg: &data[12..],
                aad: aad.as_bytes(),
            },
        )
        .map_err(|_| "Server event decryption failed (wrong key or corrupted data)".to_string())?;

    let plaintext = llamenos_core::padding::unpad(&padded)
        .map_err(|e| format!("Server event padding is malformed: {e}"))?;
    String::from_utf8(plaintext).map_err(|e| format!("Invalid UTF-8 in decrypted content: {e}"))
}

#[cfg(test)]
mod server_event_tests {
    use super::*;
    use aes_gcm::{AeadCore, aead::OsRng};

    const EPOCH: u64 = 20748;

    /// A fresh random server-event key — the tests never reuse a fixed key.
    /// Drawn straight from the AEAD's own generator, so no literal buffer
    /// ever exists that could be mistaken for key material.
    fn random_key() -> [u8; 32] {
        Aes256Gcm::generate_key(OsRng).into()
    }

    /// Seal `json` exactly as the server's `encryptEventContent` does: pad to a
    /// bucket, then AES-256-GCM under `key` with a fresh random nonce, AAD bound
    /// to the epoch, output `nonce(12) || ciphertext`, hex-encoded.
    fn seal_like_server(key: &[u8; 32], json: &str, epoch: u64) -> String {
        let padded = llamenos_core::padding::pad_to_bucket(json.as_bytes());
        let aad = format!("{LABEL_HUB_EVENT_EPOCH}:{epoch}");
        let nonce = Aes256Gcm::generate_nonce(&mut OsRng);
        let cipher = Aes256Gcm::new_from_slice(key).unwrap();
        let ct = cipher
            .encrypt(
                &nonce,
                Payload {
                    msg: &padded,
                    aad: aad.as_bytes(),
                },
            )
            .unwrap();
        let mut out = nonce.to_vec();
        out.extend_from_slice(&ct);
        hex::encode(out)
    }

    #[test]
    fn a_padded_server_event_opens_to_its_json() {
        let json = r#"{"type":"conversation:assigned","conversationId":"c1","assignedTo":"ab"}"#;
        let key = random_key();
        let keys = vec![(EPOCH, key.to_vec())];
        let opened = open_server_event(&keys, &seal_like_server(&key, json, EPOCH), EPOCH).unwrap();
        assert_eq!(opened, json);
    }

    #[test]
    fn an_event_sealed_for_another_epoch_does_not_open() {
        let json = r#"{"type":"message:new","conversationId":"c1"}"#;
        let key = random_key();
        let keys = vec![(EPOCH, key.to_vec())];
        let sealed = seal_like_server(&key, json, EPOCH + 1);
        assert!(open_server_event(&keys, &sealed, EPOCH).is_err());
        assert!(open_server_event(&keys, &sealed, EPOCH + 1).is_err());
    }

    #[test]
    fn an_event_sealed_under_another_key_does_not_open() {
        let json = r#"{"type":"message:new","conversationId":"c1"}"#;
        let keys = vec![(EPOCH, random_key().to_vec())];
        let sealed = seal_like_server(&random_key(), json, EPOCH);
        assert!(open_server_event(&keys, &sealed, EPOCH).is_err());
    }
}

