// ── Shamir Secret Sharing (GF(2^8)) ────────────────────────────────

/// GF(2^8) multiply using irreducible polynomial x^8 + x^4 + x^3 + x + 1.
fn gf256_mul(a: u8, b: u8) -> u8 {
    let mut result: u8 = 0;
    let mut aa = a;
    let mut bb = b;
    for _ in 0..8 {
        if bb & 1 != 0 {
            result ^= aa;
        }
        let carry = aa & 0x80;
        aa = aa.wrapping_shl(1);
        if carry != 0 {
            aa ^= 0x1b;
        }
        bb >>= 1;
    }
    result
}

/// GF(2^8) modular inverse via Fermat's little theorem: a^254 in GF(2^8).
fn gf256_inv(a: u8) -> u8 {
    assert!(a != 0, "Cannot invert zero in GF(256)");
    let mut result = a;
    for _ in 0..6 {
        result = gf256_mul(result, result);
        result = gf256_mul(result, a);
    }
    result = gf256_mul(result, result);
    result
}

#[derive(serde::Serialize, serde::Deserialize, Clone)]
pub struct ShamirShareJson {
    pub x: u8,
    pub y: String, // hex
}

#[derive(serde::Serialize)]
pub struct ShamirSplitResult {
    pub shares: Vec<ShamirShareJson>,
    pub commitments: Vec<String>, // SHA-256 hex
}

/// Shamir split: split a hex-encoded secret into N shares with threshold K.
/// Returns Vec of {x, y_hex} share objects and Vec of SHA-256 commitment hex strings.
/// Internal only — NOT exposed as an IPC command (secrets must not pass through the JS bridge).
fn shamir_split(secret_hex: String, total: u8, threshold: u8) -> Result<ShamirSplitResult, String> {
    if threshold < 2 || threshold > 5 {
        return Err("Threshold must be 2-5".into());
    }
    if total < 3 || total > 5 {
        return Err("Total must be 3-5".into());
    }
    if threshold > total {
        return Err("Threshold cannot exceed total".into());
    }

    let secret = hex::decode(&secret_hex).map_err(|e| e.to_string())?;
    let secret_len = secret.len();

    // Random polynomial coefficients for each byte (degree = threshold - 1)
    // coefficients[i] are the non-constant-term coefficients for the i-th degree
    let mut coefficients: Vec<Vec<u8>> = Vec::new();
    for _ in 0..threshold - 1 {
        let mut coeff = vec![0u8; secret_len];
        rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut coeff);
        coefficients.push(coeff);
    }

    let mut shares = Vec::new();
    for i in 1..=total {
        let mut y = vec![0u8; secret_len];
        for byte_idx in 0..secret_len {
            let mut val = secret[byte_idx];
            let mut x_pow = i;
            for coeff in &coefficients {
                val ^= gf256_mul(coeff[byte_idx], x_pow);
                x_pow = gf256_mul(x_pow, i);
            }
            y[byte_idx] = val;
        }
        shares.push(ShamirShareJson {
            x: i,
            y: hex::encode(&y),
        });
    }

    // SHA-256 commitments: hash(x || y)
    use sha2::Digest;
    let commitments: Vec<String> = shares
        .iter()
        .map(|s| {
            let y_bytes = hex::decode(&s.y).unwrap_or_default();
            let mut hasher = sha2::Sha256::new();
            hasher.update([s.x]);
            hasher.update(&y_bytes);
            hex::encode(hasher.finalize())
        })
        .collect();

    Ok(ShamirSplitResult {
        shares,
        commitments,
    })
}

/// Shamir combine: reconstruct the secret from >= threshold shares.
/// Internal only — NOT exposed as an IPC command (reconstructed secret must not enter JS).
fn shamir_combine(shares_json: String) -> Result<String, String> {
    let share_objs: Vec<ShamirShareJson> =
        serde_json::from_str(&shares_json).map_err(|e| e.to_string())?;
    if share_objs.len() < 2 {
        return Err("Need at least 2 shares".into());
    }

    let shares: Vec<(u8, Vec<u8>)> = share_objs
        .iter()
        .map(|s| {
            let y = hex::decode(&s.y).unwrap_or_default();
            (s.x, y)
        })
        .collect();

    let secret_len = shares[0].1.len();
    let mut result = vec![0u8; secret_len];

    for byte_idx in 0..secret_len {
        let mut val: u8 = 0;
        for i in 0..shares.len() {
            let yi = shares[i].1[byte_idx];
            let xi = shares[i].0;
            let mut lagrange: u8 = 1;
            for j in 0..shares.len() {
                if i == j {
                    continue;
                }
                let xj = shares[j].0;
                let num = xj;
                let den = xi ^ xj;
                if den == 0 {
                    return Err("Duplicate share x values".into());
                }
                lagrange = gf256_mul(lagrange, gf256_mul(num, gf256_inv(den)));
            }
            val ^= gf256_mul(yi, lagrange);
        }
        result[byte_idx] = val;
    }

    Ok(hex::encode(result))
}

/// Shamir commit: compute SHA-256 commitment for a share.
#[tauri::command]
pub fn shamir_commit(x: u8, y_hex: String) -> Result<String, String> {
    use sha2::Digest;
    let y = hex::decode(&y_hex).map_err(|e| e.to_string())?;
    let mut hasher = sha2::Sha256::new();
    hasher.update([x]);
    hasher.update(&y);
    Ok(hex::encode(hasher.finalize()))
}

/// Shamir verify: check a share against its SHA-256 commitment (constant-time).
#[tauri::command]
pub fn shamir_verify(x: u8, y_hex: String, commitment_hex: String) -> Result<bool, String> {
    let computed = shamir_commit(x, y_hex)?;
    let computed_bytes = hex::decode(&computed).map_err(|e| e.to_string())?;
    let expected_bytes = hex::decode(&commitment_hex).map_err(|e| e.to_string())?;
    if computed_bytes.len() != expected_bytes.len() {
        return Ok(false);
    }
    use subtle::ConstantTimeEq;
    Ok(computed_bytes.ct_eq(&expected_bytes).into())
}

// ── H16: Recovery group key isolation — combine+decrypt in Rust only ──

/// Generate an X25519 recovery group keypair, Shamir-split the private key, and
/// seal each share to its holder's X25519 pubkey — all inside Rust.
///
/// Returns the group public key, one sealed envelope per holder (in
/// `holder_encryption_pubkeys` order) and the share commitments. Neither the
/// private key nor any plaintext share crosses the IPC boundary: with N ≥
/// threshold plaintext shares the webview could reconstruct the group key
/// itself, which is the same as being handed the key.
#[tauri::command]
pub fn recovery_group_create(
    total: u8,
    threshold: u8,
    holder_encryption_pubkeys: Vec<String>,
) -> Result<serde_json::Value, String> {
    use x25519_dalek::{PublicKey, StaticSecret};

    if holder_encryption_pubkeys.len() != usize::from(total) {
        return Err("Exactly one holder pubkey is required per share".into());
    }

    let secret = StaticSecret::random_from_rng(rand::rngs::OsRng);
    let public = PublicKey::from(&secret);
    let secret_hex = hex::encode(secret.as_bytes());

    // Split immediately — the private key bytes are consumed here (also validates
    // total/threshold).
    let split_result = shamir_split(secret_hex, total, threshold)?;

    let mut share_envelopes = Vec::with_capacity(split_result.shares.len());
    for (share, holder_pubkey) in split_result.shares.iter().zip(&holder_encryption_pubkeys) {
        // Share plaintext: x (1 byte) || y.
        let mut plaintext = vec![share.x];
        plaintext.extend(hex::decode(&share.y).map_err(err_str)?);
        let sealed = hpke_envelope::hpke_seal(
            &plaintext,
            holder_pubkey,
            LABEL_RECOVERY_GROUP_SHARE_WRAP,
            &[],
        )
        .map_err(err_str)?;
        share_envelopes.push(serde_json::to_value(sealed).map_err(err_str)?);
    }

    Ok(serde_json::json!({
        "publicKeyHex": hex::encode(public.as_bytes()),
        "shareEnvelopes": share_envelopes,
        "commitments": split_result.commitments,
    }))
}

/// The server's record of a recovery session — the only fields Rust trusts, read
/// from `GET /api/recovery-group/session/:id` (`recoverySessionStatusResponseSchema`).
#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase")]
struct RecoverySession {
    session_id: String,
    status: String,
    /// X25519 public key of the recovering user's new device — the recipient the
    /// share is sealed to.
    new_device_pubkey: String,
}

impl RecoverySession {
    /// The server only accepts contributions in `verified`/`active` (see
    /// `RecoveryGroupService.contributeShare`); sealing a share for any other
    /// session would hand a recipient key a share the server will refuse anyway.
    fn ensure_contributable(&self) -> Result<(), String> {
        match self.status.as_str() {
            "verified" | "active" => Ok(()),
            other => Err(format!(
                "Recovery session is '{other}' — shares are only released for verified or active sessions"
            )),
        }
    }
}

/// A recovery session id as the server mints them (UUIDs). Anything else is
/// refused before it can reach a URL path, so a hostile id cannot steer Rust's
/// authenticated request to another route.
fn is_session_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 64 && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
}

/// Approve a recovery session: open this device's share, check it against its
/// commitment, seal it to the recovering user's new device, and sign the result
/// — all inside Rust, so the plaintext share never reaches the webview.
///
/// **The recipient is not an argument.** The webview names only the session;
/// Rust fetches that session from the configured, certificate-pinned backend
/// (authenticated with this device's key) and seals to the `newDevicePubkey` the
/// server holds for it. A compromised webview therefore cannot choose the key a
/// share is sealed to: it does not relay the response, cannot change the origin
/// or pins, and can only point Rust at a session the server itself lists as
/// `verified`/`active` (which needs the user's out-of-band Signal verification)
/// and that this device is entitled to read.
///
/// Returns `{ encryptedShare, signature }`. `encryptedShare` is the serialized
/// sealed envelope; `signature` covers
/// `{LABEL_RECOVERY_SHARE_CONTRIBUTE}:{session_id}:{encryptedShare}` under the
/// device signing key, so it binds the contribution to this session.
#[tauri::command]
pub async fn recovery_share_contribute_from_state(
    app: tauri::AppHandle,
    state: tauri::State<'_, CryptoState>,
    pinned: tauri::State<'_, crate::net::PinnedNet>,
    envelope: hpke_envelope::HpkeEnvelope,
    commitment_hex: String,
    session_id: String,
) -> Result<serde_json::Value, String> {
    if !is_session_id(&session_id) {
        return Err("Invalid recovery session id".into());
    }
    let path = format!("/api/recovery-group/session/{session_id}");
    let timestamp = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(err_str)?
        .as_millis() as u64;
    let token = state.auth_token_json(timestamp, "GET", &path)?;
    let body = crate::net::fetch_json(&app, &pinned, &path, &token).await?;
    let session: RecoverySession = serde_json::from_value(body)
        .map_err(|e| format!("Unexpected recovery session response: {e}"))?;
    if session.session_id != session_id {
        return Err("Server returned a different recovery session".into());
    }
    state.recovery_share_contribution(&envelope, commitment_hex, &session)
}

/// HPKE-encrypted share envelope for recovery group reconstruction.
#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct EncryptedShareEnvelope {
    pub envelope: hpke_envelope::HpkeEnvelope,
}

/// Decrypt HPKE-encrypted share envelopes using device X25519 key, combine via Shamir,
/// and store the reconstructed recovery group key in CryptoState.
/// Returns only { success: true } — NO key material enters JavaScript.
#[tauri::command]
pub fn recovery_group_reconstruct_from_shares(
    state: tauri::State<'_, CryptoState>,
    envelopes_json: String,
    label: String,
) -> Result<serde_json::Value, String> {
    let envelopes: Vec<EncryptedShareEnvelope> =
        serde_json::from_str(&envelopes_json).map_err(err_str)?;

    if envelopes.len() < 2 {
        return Err("Need at least 2 share envelopes".into());
    }

    let secret_hex = state.encryption_secret_hex()?;

    // Decrypt each HPKE envelope to get share bytes, then parse x (first byte) and y (rest)
    let mut share_objs: Vec<ShamirShareJson> = Vec::with_capacity(envelopes.len());
    for env in &envelopes {
        let aad = vec![]; // empty AAD
        let plaintext =
            hpke_envelope::hpke_open(&env.envelope, &secret_hex, &label, &aad).map_err(err_str)?;

        if plaintext.is_empty() {
            return Err("Decrypted share is empty".into());
        }

        let x = plaintext[0];
        let y = hex::encode(&plaintext[1..]);
        share_objs.push(ShamirShareJson { x, y });
    }

    // Combine shares via Shamir
    let shares_json = serde_json::to_string(&share_objs).map_err(err_str)?;
    let recovered_hex = shamir_combine(shares_json)?;
    let recovered_bytes = hex::decode(&recovered_hex).map_err(err_str)?;

    // Store in CryptoState — key NEVER enters JavaScript
    *lock_mutex(&state.recovery_group_key)? = Some(recovered_bytes);

    Ok(serde_json::json!({ "success": true }))
}

/// Decrypt a payload using the recovery group key stored in CryptoState.
/// The recovery group key is zeroized after use (one-shot).
/// Returns only the plaintext — key material never enters JavaScript.
#[tauri::command]
pub fn recovery_group_decrypt(
    state: tauri::State<'_, CryptoState>,
    ciphertext_hex: String,
    label: String,
) -> Result<String, String> {
    // Take the key out of state (zeroizes the stored copy)
    let key_bytes = lock_mutex(&state.recovery_group_key)?
        .take()
        .ok_or_else(|| {
            "No recovery group key loaded. Reconstruct from shares first.".to_string()
        })?;

    // Use the recovery group private key as X25519 secret to HPKE-open the ciphertext
    let secret_hex = hex::encode(&key_bytes);

    // Parse the ciphertext as an HPKE envelope
    let envelope: hpke_envelope::HpkeEnvelope =
        serde_json::from_str(&ciphertext_hex).map_err(err_str)?;

    let aad = vec![];
    let plaintext =
        hpke_envelope::hpke_open(&envelope, &secret_hex, &label, &aad).map_err(err_str)?;

    // key_bytes is dropped here (Vec<u8> deallocated)
    Ok(hex::encode(plaintext))
}

